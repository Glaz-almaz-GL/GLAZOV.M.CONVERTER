namespace GLAZOV.M.CONVERTER.Formats.Options;

/// <summary>
/// Clockwise rotation angle in 90-degree increments.
/// </summary>
public enum RotationAngle
{
    /// <summary>90 degrees clockwise (right).</summary>
    Degrees90 = 90,

    /// <summary>180 degrees.</summary>
    Degrees180 = 180,

    /// <summary>270 degrees clockwise (90 degrees counter-clockwise / left).</summary>
    Degrees270 = 270,
}